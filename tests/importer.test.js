'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const zlib = require('node:zlib');
const I = require('../importer.js');

// ---------- 슬라이서별 G-code 예시 ----------
const BAMBU_HEAD = `; HEADER_BLOCK_START
; BambuStudio 02.03.00.70
; model printing time: 1h 2m 3s; total estimated time: 1h 10m 5s
; total layer number: 120
; total filament length [mm] : 5012.34
; total filament volume [cm^3] : 12056.10
; total filament weight [g] : 15.23
; filament_density: 1.24
; HEADER_BLOCK_END
; CONFIG_BLOCK_START
; filament_type = PLA
; CONFIG_BLOCK_END
G28
`;

const ORCA_TAIL = `; filament used [mm] = 3200.10
; filament used [cm3] = 7.70
; filament used [g] = 9.55
; filament cost = 0.19
; total filament used [g] = 9.55
; total layers count = 80
; estimated printing time (normal mode) = 45m 30s
; filament_type = PETG
`;

const PRUSA_TAIL = `; filament used [mm] = 1000.0, 500.0
; filament used [g] = 3.00, 1.50
; estimated printing time (normal mode) = 2d 1h 0m 0s
; filament_type = PLA;PLA
; generated by PrusaSlicer 2.9.0
`;

const CURA_HEAD = `;FLAVOR:Marlin
;TIME:3723
;Filament used: 2m
;Layer height: 0.2
;Generated with Cura_SteamEngine 5.9.0
`;

test('parseDuration', () => {
  assert.equal(I.parseDuration('1h 2m 3s'), 3723);
  assert.equal(I.parseDuration('45m 30s'), 2730);
  assert.equal(I.parseDuration('2d 1h 0m 0s'), 176400);
  assert.equal(I.parseDuration('30s'), 30);
  assert.ok(Number.isNaN(I.parseDuration('abc')));
});

test('parseGcode: Bambu Studio — 총 예상 시간(예열 포함)·총 무게', () => {
  const r = I.parseGcode(BAMBU_HEAD, '');
  assert.equal(r.slicer, 'Bambu Studio');
  assert.equal(r.plates[0].seconds, 4205); // total estimated time 1h 10m 5s
  assert.equal(r.plates[0].grams, 15.23);
  assert.deepEqual(r.plates[0].types, ['PLA']);
  assert.equal(r.plates[0].estimated, false);
});

test('parseGcode: OrcaSlicer — 뒷부분 요약', () => {
  const r = I.parseGcode('; generated by OrcaSlicer 2.3.0\nG28\n', ORCA_TAIL);
  assert.equal(r.slicer, 'OrcaSlicer');
  assert.equal(r.plates[0].seconds, 2730);
  assert.equal(r.plates[0].grams, 9.55);
  assert.deepEqual(r.plates[0].types, ['PETG']);
});

test('parseGcode: PrusaSlicer — 여러 필라멘트 무게 합', () => {
  const r = I.parseGcode('G28\n', PRUSA_TAIL);
  assert.equal(r.slicer, 'PrusaSlicer');
  assert.equal(r.plates[0].grams, 4.5);
  assert.equal(r.plates[0].seconds, 176400);
  assert.deepEqual(r.plates[0].types, ['PLA', 'PLA']);
});

test('parseGcode: Cura — 길이를 무게로 환산(추정)', () => {
  const r = I.parseGcode(CURA_HEAD, '');
  assert.equal(r.slicer, 'Cura');
  assert.equal(r.plates[0].seconds, 3723);
  // 2m × π × 0.875² mm² = 4.81 cm³ × 1.24 = 5.96g
  assert.ok(Math.abs(r.plates[0].grams - 5.965) < 0.01);
  assert.equal(r.plates[0].estimated, true);
});

test('parseGcode: 정보가 없으면 알기 쉬운 오류', () => {
  assert.throws(() => I.parseGcode('G28\nG1 X10\n', ''), I.ImportError);
  assert.throws(() => I.parseGcode('', ''), /빈 파일/);
});

