test('parseSliceInfo: 플레이트별 시간·무게·재료, 슬라이스 안 된 플레이트 제외', () => {
  const r = I.parseSliceInfo(SLICE_INFO);
  assert.equal(r.client, 'slicer');
  assert.equal(r.plates.length, 2);
  const p2 = r.plates.find((p) => p.index === 2);
  assert.equal(p2.seconds, 2730);
  assert.equal(p2.grams, 11.36);
  assert.deepEqual(p2.types, ['PLA']);
  assert.equal(p2.objects, 2); // skipped 제외
  const p1 = r.plates.find((p) => p.index === 1);
  assert.equal(p1.grams, 3.5); // weight 비어 있으면 필라멘트 합
  assert.deepEqual(p1.types, ['PETG', 'PLA']);
});

// ---------- 테스트용 ZIP 만들기 ----------
function makeZip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const f of files) {
    const name = Buffer.from(f.name, 'utf8');
    const raw = Buffer.from(f.data, 'utf8');
    const data = f.store ? raw : zlib.deflateRawSync(raw);
    const method = f.store ? 0 : 8;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(method, 8);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(name.length, 26);
    locals.push(local, name, data);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(method, 10);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(raw.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, name);
    offset += 30 + name.length + data.length;
  }
  const cd = Buffer.concat(centrals);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(files.length, 8);
  eocd.writeUInt16LE(files.length, 10);
  eocd.writeUInt32LE(cd.length, 12);
  eocd.writeUInt32LE(offset, 16);
  const buf = Buffer.concat([...locals, cd, eocd]);
  return new Uint8Array(buf.buffer, buf.byteOffset, buf.byteLength);
}

test('listZip + readZipEntry: 압축(deflate)·비압축 모두', async () => {
  const zip = makeZip([
    { name: '[Content_Types].xml', data: '<Types/>', store: true },
    { name: 'Metadata/한글.txt', data: '안녕 PrintCost'.repeat(50) },
  ]);
  const entries = I.listZip(zip);
  assert.deepEqual(entries.map((e) => e.name), ['[Content_Types].xml', 'Metadata/한글.txt']);
  const text = new TextDecoder().decode(await I.readZipEntry(zip, entries[1]));
  assert.equal(text, '안녕 PrintCost'.repeat(50));
  const stored = new TextDecoder().decode(await I.readZipEntry(zip, entries[0]));
  assert.equal(stored, '<Types/>');
});

test('parse3mf: slice_info 로 플레이트 읽기 (번호순 정렬)', async () => {
  const zip = makeZip([
    { name: 'Metadata/slice_info.config', data: SLICE_INFO },
    { name: 'Metadata/plate_1.gcode', data: BAMBU_HEAD },
  ]);
  const r = await I.parse3mf(zip);
  assert.equal(r.slicer, 'Bambu Studio');
  assert.deepEqual(r.plates.map((p) => p.index), [1, 2]);
  assert.equal(r.plates[1].grams, 11.36);
});

test('parse3mf: slice_info 가 없으면 plate G-code 직접 읽기', async () => {
  const zip = makeZip([
    { name: 'Metadata/plate_2.gcode', data: '; generated by OrcaSlicer\n' + ORCA_TAIL },
    { name: 'Metadata/plate_1.gcode', data: BAMBU_HEAD },
  ]);
  const r = await I.parse3mf(zip);
  assert.deepEqual(r.plates.map((p) => [p.index, p.grams]), [[1, 15.23], [2, 9.55]]);
});

test('parse3mf: 슬라이스 안 한 프로젝트·이상한 파일은 안내 오류', async () => {
  const project = makeZip([{ name: '3D/3dmodel.model', data: '<model/>' }]);
  await assert.rejects(I.parse3mf(project), /슬라이스하지 않은 3MF/);
  await assert.rejects(I.parse3mf(new Uint8Array([1, 2, 3, 4, 5])), I.ImportError);
});

test('fileKind: 이름·첫 바이트로 판단', () => {
  const pk = new Uint8Array([0x50, 0x4b, 0x03, 0x04]);
  const gcde = new Uint8Array([0x47, 0x43, 0x44, 0x45]);
  assert.equal(I.fileKind('a.gcode.3mf', pk), '3mf');
  assert.equal(I.fileKind('a.gcode', new Uint8Array([0x3b])), 'gcode');
  assert.equal(I.fileKind('a.gcode', gcde), 'bgcode'); // 확장자만 .gcode 인 바이너리
  assert.equal(I.fileKind('a.bgcode', null), 'bgcode');
  assert.equal(I.fileKind('a.STL', null), 'model');
  assert.equal(I.fileKind('a.txt', null), 'unknown');
});

test('importFile: Blob 으로 G-code·3MF 읽기, 지원 안 하는 파일 안내', async () => {
  const gcode = Object.assign(new Blob([BAMBU_HEAD]), { name: 'x.gcode' });
  assert.equal((await I.importFile(gcode)).plates[0].grams, 15.23);
  const zip = Object.assign(new Blob([makeZip([{ name: 'Metadata/slice_info.config', data: SLICE_INFO }])]), { name: 'x.gcode.3mf' });
  assert.equal((await I.importFile(zip)).plates.length, 2);
  const stl = Object.assign(new Blob(['solid']), { name: 'x.stl' });
  await assert.rejects(I.importFile(stl), /모델 파일/);
});

test('importFile: 큰 G-code 는 앞·뒤만 읽어도 요약을 찾음', async () => {
  const middle = 'G1 X1 Y1 E0.1\n'.repeat(120000); // 약 1.7MB
  const big = Object.assign(new Blob(['; generated by PrusaSlicer\n', middle, PRUSA_TAIL]), { name: 'big.gcode' });
  const r = await I.importFile(big);
  assert.equal(r.plates[0].grams, 4.5);
});

test('splitTime: 분 반올림, 최소 1분', () => {
  assert.deepEqual(I.splitTime(4205), { hours: 1, minutes: 10 });
  assert.deepEqual(I.splitTime(2730), { hours: 0, minutes: 46 }); // 45분 30초 → 46분
  assert.deepEqual(I.splitTime(20), { hours: 0, minutes: 1 });
  assert.deepEqual(I.splitTime(0), { hours: 0, minutes: 0 });
});

test('ImportError.kind: 화면이 맞는 도움말 탭을 열 수 있게', async () => {
  const bg = Object.assign(new Blob([new Uint8Array([0x47, 0x43, 0x44, 0x45])]), { name: 'a.bgcode' });
  await assert.rejects(I.importFile(bg), (e) => e instanceof I.ImportError && e.kind === 'bgcode');
  const project = Object.assign(new Blob([makeZip([{ name: '3D/3dmodel.model', data: '<model/>' }])]), { name: 'p.3mf' });
  await assert.rejects(I.importFile(project), (e) => e.kind === 'project');
  const stl = Object.assign(new Blob(['solid']), { name: 'x.stl' });
  await assert.rejects(I.importFile(stl), (e) => e.kind === 'model');
});
